"""STEP 6 - EXPLORATORY DATA ANALYSIS (EDA).

Run:  python notebooks/eda.py
Creates 4 charts in reports/figures/ and a short text summary in reports/insights.md.
In VS Code you can also run it cell by cell (each "# %%" line starts a cell).
"""
# %% Setup
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from src.config import REPORTS_DIR
from src.load import read_air_quality

FIG = REPORTS_DIR / "figures"
FIG.mkdir(parents=True, exist_ok=True)
try:
    df = read_air_quality()
except Exception:
    sys.exit("No data found. Run  python run_pipeline.py  first (or add --sample to test with fake data).")
print(f"Loaded {len(df)} rows, {df['area'].nunique()} areas, {df['obs_time'].min()} to {df['obs_time'].max()}")

# %% Chart 1 - daily average PM2.5 per area
daily = df.groupby(["obs_date", "area"])["pm2_5"].mean().unstack()
ax = daily.plot(figsize=(10, 4.5), linewidth=1.5)
ax.set_title("Daily average PM2.5 by area")
ax.set_ylabel("PM2.5 (ug/m3)")
ax.set_xlabel("")
plt.xticks(rotation=45)
plt.tight_layout()
plt.savefig(FIG / "1_daily_trend.png", dpi=130)
plt.close()

# %% Chart 2 - heatmap: hour of day vs day of week
pivot = df.pivot_table(index="hour_of_day", columns="day_of_week", values="pm2_5", aggfunc="mean")
fig, ax = plt.subplots(figsize=(7, 6))
image = ax.imshow(pivot.values, aspect="auto", cmap="YlOrRd", origin="lower")
ax.set_xticks(range(7), ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"])
ax.set_yticks(range(0, 24, 3))
ax.set_ylabel("Hour of day")
ax.set_title("Average PM2.5 by hour and weekday")
fig.colorbar(image, label="PM2.5 (ug/m3)")
plt.tight_layout()
plt.savefig(FIG / "2_hour_weekday_heatmap.png", dpi=130)
plt.close()

# %% Chart 3 - average PM2.5 per area
by_area = df.groupby("area")["pm2_5"].mean().sort_values()
ax = by_area.plot(kind="barh", figsize=(7, 4), color="#c0504d")
ax.set_title("Average PM2.5 by area")
ax.set_xlabel("PM2.5 (ug/m3)")
plt.tight_layout()
plt.savefig(FIG / "3_area_comparison.png", dpi=130)
plt.close()

# %% Chart 4 - correlation with weather
cols = ["pm2_5", "pm10", "nitrogen_dioxide", "ozone", "temperature_2m",
        "relative_humidity_2m", "wind_speed_10m", "precipitation"]
corr = df[cols].corr()
fig, ax = plt.subplots(figsize=(7.5, 6.5))
image = ax.imshow(corr.values, cmap="coolwarm", vmin=-1, vmax=1)
ax.set_xticks(range(len(cols)), cols, rotation=60, ha="right")
ax.set_yticks(range(len(cols)), cols)
for i in range(len(cols)):
    for j in range(len(cols)):
        ax.text(j, i, f"{corr.values[i, j]:.2f}", ha="center", va="center", fontsize=7)
ax.set_title("Correlation between pollutants and weather")
fig.colorbar(image)
plt.tight_layout()
plt.savefig(FIG / "4_correlation.png", dpi=130)
plt.close()

# %% Insights written automatically from the data (so they are never made up)
hourly = df.groupby("hour_of_day")["pm2_5"].mean()
weekend = df.groupby("is_weekend")["pm2_5"].mean()
wind_corr = df["pm2_5"].corr(df["wind_speed_10m"])
hum_corr = df["pm2_5"].corr(df["relative_humidity_2m"])
poor_share = (df["pm2_5"] > 90).mean() * 100
lines = [
    "# Key findings (generated by notebooks/eda.py)",
    "",
    f"- Data: {len(df):,} hourly rows, {df['obs_time'].min():%d %b %Y} to {df['obs_time'].max():%d %b %Y}.",
    f"- Most polluted area on average: **{by_area.index[-1]}** ({by_area.iloc[-1]:.1f} ug/m3). "
    f"Cleanest: **{by_area.index[0]}** ({by_area.iloc[0]:.1f} ug/m3).",
    f"- Worst hour of the day: **{hourly.idxmax()}:00** ({hourly.max():.1f} ug/m3). "
    f"Best hour: **{hourly.idxmin()}:00** ({hourly.min():.1f} ug/m3).",
]
if 0 in weekend.index and 1 in weekend.index:
    diff = (weekend[1] - weekend[0]) / weekend[0] * 100
    lines.append(f"- Weekends vs weekdays: PM2.5 is {diff:+.1f}% on weekends.")
lines += [
    f"- Correlation of PM2.5 with wind speed: {wind_corr:.2f}; with humidity: {hum_corr:.2f}.",
    f"- {poor_share:.1f}% of all hours were above 90 ug/m3 (CPCB 'Poor' or worse).",
]
(REPORTS_DIR / "insights.md").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
